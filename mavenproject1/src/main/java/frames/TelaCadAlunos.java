    private void carregarAluno() throws SQLException {
        List<String[]> alunos = autenticacao.listarAlunos();

        DefaultTableModel tabela = (DefaultTableModel) tblAlunos.getModel();
        tabela.setRowCount(0);

        for (String[] aluno : alunos) {
            tabela.addRow(aluno);
        }
    }
