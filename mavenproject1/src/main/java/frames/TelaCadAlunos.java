    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed

        try {

            String nome = txtNomeCompleto.getText().trim();
            String cpf = txtCPF.getText().trim();
            String email = txtEmail.getText().trim();
            String matricula = txtMatricula.getText().trim();

            if ((nome.isEmpty() || nome.isBlank()) || (cpf.isEmpty() || cpf.isBlank()) || (email.isEmpty() || email.isBlank()) || (matricula.isEmpty() || matricula.isBlank())) {
                JOptionPane.showMessageDialog(this, "Todos os campos devem ser preenchidos");
                txtNomeCompleto.setBorder(new LineBorder(Color.RED, 1));
                txtCPF.setBorder(new LineBorder(Color.RED, 1));
                txtEmail.setBorder(new LineBorder(Color.RED, 1));
                txtMatricula.setBorder(new LineBorder(Color.RED, 1));
            } else {
                int confirmacao = JOptionPane.showConfirmDialog(
                        this, "Confirme os campos para cadastrar:\nNome: " + nome + "\nMatrícula: " + matricula + "\nCPF: " + cpf + "\nE-mail: " + email);

                if (confirmacao != JOptionPane.YES_OPTION) {
                    return;
                }

                boolean sucesso = autenticacao.StudentManagement(matricula, nome, cpf, email);

                if (sucesso) {
                    JOptionPane.showMessageDialog(this, "Registro realizado com sucesso.");
                    txtNomeCompleto.setText("");
                    txtMatricula.setText("");
                    txtCPF.setText("");
                    txtEmail.setText("");
                } else {
                    JOptionPane.showMessageDialog(this, "Erro no registro");
                }
            }

        } catch (SQLException ex) {
            Logger.getLogger(TelaCadAlunos.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnGerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGerarActionPerformed
        try {
            int tamanho = 4;

            String caracteres = "1234567890";
            Random random = new Random();
            StringBuilder matricula = new StringBuilder();

            for (int i = 0; i < tamanho; i++) {
                int indice = random.nextInt(caracteres.length());
                matricula.append(caracteres.charAt(indice));

            }
            String user = "A" + matricula;
            txtMatricula.setText(user.toString());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Erro de processamento");
        }
    }//GEN-LAST:event_btnGerarActionPerformed

    private void btnDeletarContaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletarContaActionPerformed
        String cpf = JOptionPane.showInputDialog(this, "Digite seu CPF para exclusão");
        if (cpf == null || cpf.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "CPF obrigatório");
            return;
        }
        int confirmacao = JOptionPane.showConfirmDialog(this, "Deseja excluir o usuário: " + cpf + "?", "Excluir conta", JOptionPane.YES_NO_OPTION);
        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (autenticacao.deletarConta(cpf)) {
                JOptionPane.showMessageDialog(this, "Usuário deletado com sucesso!");
            } else {
                JOptionPane.showMessageDialog(this, "Não foi possível deletar o usuário");
            }
        } catch (SQLException ex) {
            Logger.getLogger(TelaCadAlunos.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnDeletarContaActionPerformed

